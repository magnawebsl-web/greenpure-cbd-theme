                foreach ( $sku_image_map as $prefix => $img ) {
                    if ( strpos($p['sku'], $prefix) === 0 ) { $svg_file = $img; break; }
                }
            }
            $svg_file = $svg_file ?? ($cat_image_map[$p['cat']] ?? 'huile-cbd-10.svg');
            $attach_id = greenpure_attach_product_svg($svg_file, $product_id, $p['name']);
            if ($attach_id && ! is_wp_error($attach_id)) {
                set_post_thumbnail($product_id, $attach_id);
            }
        }
    }

    // Vider les caches WooCommerce
    wc_delete_product_transients();

    do_action('greenpure_demo_installed');
}

/**
 * Attache un fichier SVG depuis assets/images/products/ comme image de produit.
 * Crée l'attachement WordPress (copie dans wp-content/uploads) si non existant.
 *
 * @param string $svg_filename  Nom du fichier SVG (ex: 'huile-cbd.svg')
 * @param int    $product_id    ID du produit parent
 * @param string $alt_text      Texte alternatif pour l'image
 * @return int|WP_Error         ID de l'attachement ou WP_Error
 */
function greenpure_attach_product_svg( $svg_filename, $product_id, $alt_text = '' ) {
    $source_file = get_template_directory() . '/assets/images/products/' . $svg_filename;

    if ( ! file_exists( $source_file ) ) {
        return new WP_Error( 'missing_svg', 'SVG source file not found: ' . $svg_filename );
    }

    // Vérifier si on a déjà uploadé ce SVG (cache par nom de fichier)
    $cache_key = 'greenpure_svg_attach_' . sanitize_key( $svg_filename );
    $cached_id = get_option( $cache_key );
    if ( $cached_id && get_post( $cached_id ) ) {
        return (int) $cached_id;
    }

    $upload_dir = wp_upload_dir();
    $dest_dir   = $upload_dir['path'] . '/greenpure-cbd/';
    $dest_file  = $dest_dir . $svg_filename;

    if ( ! file_exists( $dest_dir ) ) {
        wp_mkdir_p( $dest_dir );
    }

    if ( ! file_exists( $dest_file ) ) {
        if ( ! copy( $source_file, $dest_file ) ) {
            return new WP_Error( 'copy_failed', 'Could not copy SVG to uploads: ' . $dest_file );
        }
    }

    $file_url = $upload_dir['url'] . '/greenpure-cbd/' . $svg_filename;

    $attachment = [
        'post_mime_type' => 'image/svg+xml',
        'post_title'     => sanitize_file_name( $alt_text ?: $svg_filename ),
        'post_content'   => '',
        'post_status'    => 'inherit',
        'post_parent'    => $product_id,
        'guid'           => $file_url,
    ];

    $attach_id = wp_insert_attachment( $attachment, $dest_file, $product_id );

    if ( ! is_wp_error( $attach_id ) ) {
        // Générer les métadonnées (dimensions pour SVG = 0 sans bibliothèque SVG)
        require_once ABSPATH . 'wp-admin/includes/image.php';
        $attach_data = wp_generate_attachment_metadata( $attach_id, $dest_file );
        wp_update_attachment_metadata( $attach_id, $attach_data );
        update_post_meta( $attach_id, '_wp_attachment_image_alt', esc_attr( $alt_text ) );

        update_option( $cache_key, $attach_id );
    }

    return $attach_id;
}
